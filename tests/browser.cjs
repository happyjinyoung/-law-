const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
const fs=require('node:fs');
(async()=>{
const browser=await chromium.launch({headless:true});const page=await browser.newPage({viewport:{width:430,height:950},timezoneId:'Asia/Seoul'});
const failures=[];page.on('pageerror',e=>failures.push(e.message));
await page.goto('http://127.0.0.1:8766');
const original=page.frameLocator('#original'),added=page.frameLocator('#service');
await original.locator('#today-text').waitFor();
await page.waitForFunction(()=>Boolean(document.querySelector('#original').contentDocument.querySelector('script[src="/original-bridge.js"]')));
assert.equal(await original.locator('#cam-input').getAttribute('capture'),'environment');
assert.equal(await original.locator('#cam-input').getAttribute('accept'),'image/*');
const oldFrame=page.frames().find(f=>f.url().endsWith('/index.html'));
await oldFrame.evaluate(()=>{localStorage.removeItem('sg_custom');navigateTo('contracts');openAdd('보존 검증 계약');});
await original.locator('#add-label').fill('원본 일정 보존');await original.locator('#add-date').fill('2027-03-02');await oldFrame.evaluate(()=>submitAdd());
assert.ok(await oldFrame.evaluate(()=>localStorage.getItem('sg_custom').includes('원본 일정 보존')));
await oldFrame.evaluate(()=>navigateTo('analyze-start'));
await original.locator('#file-input').setInputFiles(path.resolve(__dirname,'../work/fictional.pdf'));
await original.locator('#capture-file-name').filter({hasText:'fictional.pdf'}).waitFor();
await page.locator('#transfer').click();
await added.locator('#contract-text').waitFor();
assert.ok((await added.locator('#contract-text').inputValue()).includes('2030'));
await added.locator('#confirm-source').check();await added.locator('[data-action="analyze"]').click();await added.getByRole('heading',{name:'분석 완료',exact:true}).waitFor();
await added.locator('[data-action="save"]').click();await added.getByRole('button',{name:'저장한 계약 조회'}).click();
await page.locator('#original-tab').click();
await oldFrame.evaluate(()=>startAnalysis());await original.locator('#analysis-fields').waitFor({state:'visible'});
await page.locator('#transfer').click();await added.locator('#contract-text').waitFor({state:'visible'});
assert.ok((await added.locator('#contract-text').inputValue()).includes('지급'));
await page.reload();await original.locator('#today-text').waitFor();
const restored=page.frames().find(f=>f.url().endsWith('/index.html'));
assert.ok(await restored.evaluate(()=>localStorage.getItem('sg_custom').includes('원본 일정 보존')));
await page.locator('#service-tab').click();await added.locator('#menu-button').click();await added.locator('#menu [data-go="contracts"]').click();await added.locator('.contract-open').first().waitFor();
assert.deepEqual(failures,[]);
fs.mkdirSync(path.resolve(__dirname,'../work'),{recursive:true});
await page.screenshot({path:path.resolve(__dirname,'../work/added-screen.png'),fullPage:true,animations:'disabled'});
await page.locator('#original-tab').click();await original.locator('#screen-home h1').waitFor({state:'visible'});await page.waitForTimeout(250);await page.screenshot({path:path.resolve(__dirname,'../work/original-screen.png'),fullPage:true,animations:'disabled'});
await browser.close();console.log('Additive browser integration: passed / original camera input, PDF.js extraction, field correction, text handoff, added analysis/save, both stores restored.');
})().catch(e=>{console.error(e);process.exit(1)});
